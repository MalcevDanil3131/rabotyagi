export function workflowStageIndex(status: ApiStatus): number {
  if (status === 'cancelled') return -1;
  const index = workflowStages.findIndex((stage) => stage.statuses.includes(status));
  return index === -1 ? 0 : index;
}

/**
 * Выбирает роль, для которой сейчас полезнее показать подсказку.
 * Участник заявки важнее служебной роли: клиент видит подсказки заказчика,
 * назначенный мастер — подсказки исполнителя.
 */
export function resolveHintRole({
  status,
  roles,
  isInitiator,
  isExecutor,
}: HintContext): WorkflowRole {
  const isWorker = roles.includes('Worker');
  const isDispatcher = roles.includes('Dispatcher') || roles.includes('SuperAdmin');
  const isAdmin = roles.includes('Admin') || roles.includes('SuperAdmin');
  if (isExecutor && isWorker) return 'worker';
  if (isInitiator) return 'client';
  if (status === 'approved' && isAdmin) return 'admin';
  if (isDispatcher) return 'dispatcher';
  if (isAdmin) return 'admin';
  if (isWorker) return 'worker';
  return 'client';
}

